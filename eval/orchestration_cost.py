#!/usr/bin/env python3
"""Estimated payload cost of four support workers: naive fan-out vs the lean pipeline.

Offline and deterministic. It generates a linked fictional vault, indexes it,
and simulates one coordinator with four workers that each need evidence for a
related sub-question. It then counts, in estimated tokens (ceil(chars / 4)):

  initial worker payloads
    naive       the full rule file + the objective + the full text of every file
                the worker's own FTS search surfaced (top 3)
    lean-own    worker core + job + input manifest + a packet built for that
                worker's own sub-question (compact synaptic, budget 1,200)
    lean-shared worker core + job + input manifest + one shared packet the
                coordinator built once (compact synaptic, budget 2,000, top 6),
                counted again for every worker that reads it

The packets are compact synaptic packets (`packet build --method synaptic
--compact --budget-tokens N`), the budget-sized packets docs/subagents.md
describes; `--packet default` measures the default synaptic packet (the fts
packet plus link-graph extras within --extra-tokens) instead.

  root verification reading
    naive       every worker's full report + the full text of every cited source
                (to confirm the quotes)
    lean        receipts + the `handback check` summary + K sampled records with
                their cited lines + the cited lines of one critical record per worker

These are estimated payload tokens on a synthetic setup: not billed host tokens,
not a tokenizer count and not evidence about answer quality. Worker returns are
synthesised from the evidence each worker received; no model runs. The output is
deterministic: fixed generator seeds, a fixed sample seed, no clock or path in
any counted text that changes its length.

Usage: python3 eval/orchestration_cost.py [--standin | --rules FILE] [--sample K]
                                          [--packet compact|default] [--json]
       python3 eval/orchestration_cost.py --docs   (the generated block of docs/subagents.md §5)
Python 3.10+; standard library only.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import random
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from context_layer import orchestrate as orch  # noqa: E402

TEMPLATE_RULES = ROOT / "templates" / "vault" / "CLAUDE.md"
STANDIN_LINES = 250
OWN_BUDGET = 1200        # --budget-tokens of each worker's own compact packet
SHARED_BUDGET = 2000     # --budget-tokens of the coordinator's shared compact packet
SHARED_TOP_K = 6
DOCS_BEGIN = "<!-- BEGIN generated by `python3 eval/orchestration_cost.py --docs` -->"
DOCS_END = "<!-- END generated -->"

ROUTES = {"record_type_allowlist": ["verbatim_text_file"],
          "routes": {"notes": {"priority": 1, "triggers": ["note"], "canonical_sources": [],
                               "path_hints": []}},
          "fallback_routes": [], "aliases": {}, "exclude_prefixes": []}

WORDS = ("tide harbor pier lantern ledger survey ferry keel mooring buoy channel dredge "
         "gantry quay bollard signal chart shoal inlet breakwater crane rope net hull "
         "crew shift season report draft note review minutes plan item follow owner").split()

ROOT_GOAL = "Decide whether the beacon retrofit can start this season."
UMBRELLA = ("beacon retrofit approved budget, lamp supplier lead time, schedule risks, "
            "approval date")
# (worker objective, gold file, gold sentence) - the fact each worker must locate.
WORKERS = [
    ("What budget did the harbor board approve for the beacon retrofit?",
     "decisions/retrofit-budget.md",
     "The harbor board approved a budget of 48,000 credits for the beacon retrofit."),
    ("Which supplier provides the beacon lamp assembly and what is its lead time?",
     "suppliers/lumen-works.md",
     "Lumen Works supplies the beacon lamp assembly with a lead time of eleven weeks."),
    ("What schedule risks were raised for the beacon retrofit?",
     "meetings/retrofit-risk-review.md",
     "Schedule risk: the pier survey may slip into the storm season and delay the retrofit."),
    ("Who approved the beacon retrofit and on which date?",
     "decisions/retrofit-approval.md",
     "Board chair Iris Vale approved the beacon retrofit on 14 March."),
]


def filler(rng: random.Random, sentences: int) -> str:
    out = []
    for _ in range(sentences):
        words = [rng.choice(WORDS) for _ in range(rng.randint(9, 16))]
        out.append(" ".join(words).capitalize() + ".")
    return " ".join(out)


def note(rng: random.Random, title: str, fact: str | None, links: list, paragraphs: int) -> str:
    body = [f"# {title}", ""]
    fact_at = rng.randrange(paragraphs) if fact else -1
    for index in range(paragraphs):
        body.append(filler(rng, rng.randint(3, 5)))
        if index == fact_at:
            body.append(fact)
        body.append("")
    if links:
        body.append("Related: " + ", ".join(f"[[{link}]]" for link in links) + ".")
        body.append("")
    return "\n".join(body)


def generate(vault: Path) -> None:
    """A fictional harbor-works vault: 4 gold notes, a hub, and 40 distractors."""
    rng = random.Random(50)
    files = {
        "projects/beacon-retrofit.md": note(
            rng, "Beacon retrofit", "The beacon retrofit replaces the lamp assembly on the "
            "north pier beacon.", ["decisions/retrofit-budget", "suppliers/lumen-works",
                                   "meetings/retrofit-risk-review",
                                   "decisions/retrofit-approval"], 5),
    }
    for _, path, fact in WORKERS:
        files[path] = note(rng, Path(path).stem.replace("-", " ").title(), fact,
                           ["projects/beacon-retrofit"], rng.randint(4, 7))
    folders = ["projects", "decisions", "suppliers", "meetings", "people", "logs"]
    for number in range(40):
        folder = folders[number % len(folders)]
        # Distractors share vocabulary with the questions, as a real vault would.
        topic = rng.choice(["budget", "supplier", "schedule", "risk", "approval", "lamp",
                            "retrofit", "board"])
        fact = f"The {topic} for item {number} is tracked in the {folder} ledger."
        links = [f"{folders[(number + 1) % 6]}/item-{(number + 1) % 40:02d}"]
        if number % 7 == 0:
            links.append("projects/beacon-retrofit")
        files[f"{folder}/item-{number:02d}.md"] = note(rng, f"Item {number:02d}", fact, links,
                                                       rng.randint(4, 9))
    for name, text in files.items():
        path = vault / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    (vault / ".context").mkdir(exist_ok=True)
    (vault / ".context" / "routes.json").write_text(json.dumps(ROUTES), encoding="utf-8")


def standin_rules() -> str:
    """A 250-line stand-in for a vault rule file (about 47 characters per line)."""
    rng = random.Random(250)
    lines = ["# Vault rules", ""]
    while len(lines) < STANDIN_LINES:
        words = [rng.choice(WORDS) for _ in range(rng.randint(5, 9))]
        lines.append("- " + " ".join(words).capitalize() + ".")
    return "\n".join(lines[:STANDIN_LINES]) + "\n"


def cited_lines(vault: Path, record: dict) -> str:
    lines = orch.lines_of((vault / record["source_path"]).read_text(encoding="utf-8"))
    return "".join(lines[record["line_start"] - 1:record["line_end"]])


def worker_records(vault: Path, passages: list, gold: tuple, fabricate: bool) -> list:
    """What a worker might return: one record per passage, the gold fact if present."""
    records = []
    for item in passages:
        text = (vault / item["source_path"]).read_text(encoding="utf-8")
        lines = orch.lines_of(text)
        start, end = item.get("line_start", 1), item.get("line_end", len(lines))
        chosen = None
        for number in range(start, end + 1):
            line = lines[number - 1].strip()
            if gold[1] in line:
                chosen = (number, gold[1])
                break
            if chosen is None and line and not line.startswith(("#", "Related:")):
                chosen = (number, line[:120])
        if chosen is None:
            continue
        records.append({"id": f"E{len(records) + 1}", "observation": "candidate passage",
                        "source_path": item["source_path"],
                        "source_sha256": orch.sha256_bytes(text.encode("utf-8")),
                        "line_start": chosen[0], "line_end": chosen[0], "span": chosen[1],
                        "method": "read packet", "uncertainty": "relevance not judged"})
    if fabricate and records:
        fake = dict(records[0], id=f"E{len(records) + 1}",
                    span=records[0]["span"].replace("a", "o", 1) + " (paraphrased)")
        records.append(fake)
    return records


def report_markdown(objective: str, records: list) -> str:
    """The naive return: the same records as a prose-free Markdown report."""
    out = [f"# Report: {objective}", "", "## Findings", ""]
    for r in records:
        out += [f"### {r['id']}", f"Observation: {r['observation']}.",
                f"Quote: \"{r['span']}\"",
                f"Source: {r['source_path']} lines {r['line_start']}-{r['line_end']} "
                f"sha256 {r['source_sha256']}", ""]
    out += ["## Summary", "", " ".join(f"{r['id']}: {r['span']}" for r in records), ""]
    return "\n".join(out)


def packet(vault: Path, prompt: str, budget: int, mode: str, top_k: int = 3) -> dict:
    """A synaptic packet: compact and sized by `budget`, or the default fts-plus-extras one."""
    if mode == "compact":
        return orch.build_packet(vault, prompt, "synaptic", budget_tokens=budget, top_k=top_k,
                                 compact=True)
    return orch.build_packet(vault, prompt, "synaptic", top_k=top_k)


def run(rules_text: str, rules_label: str, sample_k: int, mode: str = "compact") -> dict:
    temp = tempfile.TemporaryDirectory()
    vault = Path(temp.name).resolve() / "vault"
    vault.mkdir()
    generate(vault)
    env = dict(os.environ, HOME=str(vault.parent))
    done = subprocess.run([sys.executable, "-m", "context_layer.cli", "index", str(vault)],
                          cwd=ROOT, capture_output=True, text=True, env=env)
    if done.returncode != 0:
        raise SystemExit(done.stderr)
    est = orch.est_tokens
    notes = sum(1 for _ in vault.rglob("*.md"))
    shared = packet(vault, UMBRELLA, SHARED_BUDGET, mode, top_k=SHARED_TOP_K)
    arms = {"naive": [], "lean-own": [], "lean-shared": []}
    covered = {name: 0 for name in arms}
    verification = {"naive": 0, "lean": 0}
    fabricated_caught = 0
    per_worker = []
    for number, (objective, gold_path, gold_fact) in enumerate(WORKERS, 1):
        # (a) naive: whole rule file + objective + full text of what its own search surfaced.
        found = orch._retrieve(vault, objective, "fts", 3, 6000, 2000, 1200)
        surfaced = list(dict.fromkeys(item["source_path"] for item in found["evidence"]))
        texts = [(vault / name).read_text(encoding="utf-8") for name in surfaced]
        naive = est(rules_text) + est(objective) + sum(est(t) for t in texts)
        arms["naive"].append(naive)
        covered["naive"] += any(gold_fact in t for t in texts)
        # (b) lean-own: packet for this sub-question only.
        own = packet(vault, objective, OWN_BUDGET, mode)
        lean_own = job_payload(vault, f"own-{number}", objective, own["id"])
        arms["lean-own"].append(lean_own["total"])
        covered["lean-own"] += any(gold_fact in e["content"] for e in own["packet"]["evidence"])
        # (c) lean-shared: the coordinator's one packet.
        report = orch.new_job(vault, **job_args(f"shared-{number}", objective, shared["id"]))
        payload = report["payload"]
        arms["lean-shared"].append(payload["total"])
        covered["lean-shared"] += any(gold_fact in e["content"]
                                      for e in shared["packet"]["evidence"])
        # Worker returns, synthesised from what the lean-shared worker received.
        job_path = vault / report["job_path"]
        job, _ = orch.parse_job(job_path.read_text(encoding="utf-8"))
        out = vault / job["owned_output_dir"]
        out.mkdir(parents=True)
        records = worker_records(vault, shared["packet"]["evidence"], (gold_path, gold_fact),
                                 fabricate=number == 3)
        (out / "evidence.jsonl").write_text("".join(json.dumps(r) + "\n" for r in records),
                                            encoding="utf-8")
        receipt = {"schema": orch.SCHEMA_RECEIPT, "task_id": job["task_id"], "attempt": 1,
                   "state": "READY", "counts": {"records": len(records),
                                                "scanned": len(shared["packet"]["evidence"]),
                                                "excluded": 0, "failed": 0},
                   "handoff": "handoff.md", "blocker": None}
        receipt_text = json.dumps(receipt)
        (out / "receipt.json").write_text(receipt_text, encoding="utf-8")
        check = orch.check_handback(out, job_file=job_path, k=sample_k, seed="eval-root-draw")
        fabricated_caught += check["failed"]
        # Naive verification: whole report + whole text of every cited source.
        cited = {r["source_path"] for r in records}
        naive_verify = est(report_markdown(objective, records)) + sum(
            est((vault / name).read_text(encoding="utf-8")) for name in cited)
        # Lean verification: receipt + check summary + sampled records with their lines
        # + the cited lines of one critical record (the gold fact, when the worker has it).
        summary = orch.render_check({**check, "sample": {**check["sample"], "k": 0}})
        sampled = sum(est(json.dumps(r)) + est(cited_lines(vault, r))
                      for r in check["sample"]["records"])
        critical = [r for r in records if r["span"] == gold_fact][:1] or records[:1]
        lean_verify = est(receipt_text) + est(summary) + sampled + sum(
            est(json.dumps(r)) + est(cited_lines(vault, r)) for r in critical)
        verification["naive"] += naive_verify
        verification["lean"] += lean_verify
        per_worker.append({"worker": number, "naive_payload": naive,
                           "lean_own_payload": lean_own["total"],
                           "lean_own_parts": lean_own["parts"],
                           "lean_shared_payload": payload["total"],
                           "lean_shared_parts": payload["parts"], "records": len(records),
                           "check_failed": check["failed"], "naive_verify": naive_verify,
                           "lean_verify": lean_verify, "surfaced": surfaced})
    temp.cleanup()
    return {"rules": rules_label, "rules_est_tokens": est(rules_text),
            "rules_lines": rules_text.count("\n"), "vault_notes": notes,
            "packets": mode, "own_budget_tokens": OWN_BUDGET if mode == "compact" else None,
            "shared_budget_tokens": SHARED_BUDGET if mode == "compact" else None,
            "shared_packet_est_tokens": shared["est_tokens"],
            "shared_packet_passages": len(shared["packet"]["evidence"]),
            "totals": {name: sum(values) for name, values in arms.items()},
            "gold_fact_in_payload": covered, "verification": verification,
            "fabricated_records_planted": 1, "records_failing_check": fabricated_caught,
            "sample_k": sample_k, "per_worker": per_worker}


def job_args(task_id: str, objective: str, packet_id: str) -> dict:
    return dict(objective=objective, packet_id=packet_id, root_goal=ROOT_GOAL,
                allowed_roots=["."], exclusions=[], known_unknowns=[], method=None,
                acceptance="one record quoting the fact verbatim, or BLOCKED",
                stop_when="the fact has a record, or the packet lacks it (report PARTIAL)",
                out=None, task_id=task_id, attempt=1, max_total_tokens=20000,
                max_seconds=600, allow_over=True)


def job_payload(vault: Path, task_id: str, objective: str, packet_id: str) -> dict:
    return orch.new_job(vault, **job_args(task_id, objective, packet_id))["payload"]


def table(result: dict) -> str:
    totals, verify = result["totals"], result["verification"]
    base = totals["naive"]
    rows = [
        "| Arm (4 workers) | Initial worker payload, est. tokens | vs naive | Gold fact in payload |",
        "| --- | ---: | ---: | ---: |"]
    for name in ("naive", "lean-own", "lean-shared"):
        rows.append(f"| {name} | {totals[name]:,} | {totals[name] / base:.0%} | "
                    f"{result['gold_fact_in_payload'][name]}/4 |")
    rows += ["", "| Root verification reading | est. tokens |", "| --- | ---: |",
             f"| naive: 4 full reports + full text of every cited source | {verify['naive']:,} |",
             f"| lean: receipts + `handback check` summary + {result['sample_k']} sampled "
             f"records/worker with cited lines + 1 critical record/worker | {verify['lean']:,} |"]
    return "\n".join(rows)


def fixed_part(result: dict) -> dict:
    """Mean est. tokens of core, job and manifest per worker (lean-shared payloads)."""
    parts = [worker["lean_shared_parts"] for worker in result["per_worker"]]
    return {name: round(sum(p[name] for p in parts) / len(parts))
            for name in ("core", "job", "manifest")}


def docs_block(standin: dict, template: dict, default: dict) -> str:
    """The measured part of docs/subagents.md §5, generated from three `--json` results:
    the stand-in and the template rule file with compact packets, and the stand-in
    with `--packet default`."""
    def arm_rows(result, long_labels):
        base = result["totals"]["naive"]
        labels = {
            "naive": "naive: full rule file + objective + full text of the 3 files its own "
                     "FTS search surfaced",
            "lean-own": "lean-own: core + job + manifest + a compact synaptic packet for its "
                        f"own sub-question (budget {result['own_budget_tokens']:,})",
            "lean-shared": "lean-shared: core + job + manifest + one shared compact synaptic "
                           f"packet (budget {result['shared_budget_tokens']:,}; "
                           f"{result['shared_packet_passages']} passages, "
                           f"{result['shared_packet_est_tokens']:,} est. tokens), counted once "
                           "per worker"}
        rows = []
        for name in ("naive", "lean-own", "lean-shared"):
            label = labels[name] if long_labels else name
            cells = [label, f"{result['totals'][name]:,}",
                     f"{result['totals'][name] / base:.0%}"]
            if long_labels:
                cells.append(f"{result['gold_fact_in_payload'][name]}/4")
            rows.append("| " + " | ".join(cells) + " |")
        return rows

    for result in (standin, template):
        if result["packets"] != "compact":
            raise ValueError("the docs tables are measured with compact packets")
    if default["packets"] != "default" or default["rules"] != standin["rules"]:
        raise ValueError("the comparison run is the stand-in with --packet default")
    verify = standin["verification"]
    fixed = fixed_part(standin)
    lines = [DOCS_BEGIN, "", "```", "python3 eval/orchestration_cost.py --standin", "```", "",
             f"The rule file a naive worker loads is a {standin['rules']}: "
             f"{standin['rules_lines']} lines, {standin['rules_est_tokens']:,} estimated tokens.",
             "", "| Arm (4 workers) | Initial worker payload, est. tokens | vs naive "
             "| Gold fact in payload |", "| --- | ---: | ---: | ---: |"]
    lines += arm_rows(standin, True)
    lines += ["", "| Root verification reading | est. tokens |", "| --- | ---: |",
              f"| naive: 4 full reports + full text of every cited source "
              f"| {verify['naive']:,} |",
              f"| lean: receipts + `handback check` summary + {standin['sample_k']} sampled "
              "records per worker with their cited lines + 1 critical record per worker with "
              f"its lines | {verify['lean']:,} |", "",
              f"`handback check` caught {standin['records_failing_check']} of the "
              f"{standin['fabricated_records_planted']} planted fabricated record(s).", "",
              "```", f"python3 eval/orchestration_cost.py --rules {template['rules']}", "```", "",
              f"This run uses the vault rule template: {template['rules_lines']} lines, "
              f"{template['rules_est_tokens']:,} estimated tokens.", "",
              "| Arm | Initial worker payload, est. tokens | vs naive |",
              "| --- | ---: | ---: |"]
    lines += arm_rows(template, False)
    same = template["verification"] == verify
    lines += ["", ("Verification reading is the same as above " if same else
                   "Verification reading: ")
              + f"({template['verification']['naive']:,} vs {template['verification']['lean']:,}).",
              "", "The fixed part of every lean payload is the worker core "
              f"({fixed['core']:,} est. tokens), the job (about {fixed['job']:,}) and the input "
              f"manifest (about {fixed['manifest']:,}): about "
              f"{sum(fixed.values()):,} est. tokens per worker.", "",
              "```", "python3 eval/orchestration_cost.py --standin --packet default", "```",
              "", "With the default synaptic packet (the fts packet plus link-graph extras, "
              "not sized to a token budget) the stand-in run gives lean-own "
              f"{default['totals']['lean-own']:,} and lean-shared "
              f"{default['totals']['lean-shared']:,} est. tokens against naive "
              f"{default['totals']['naive']:,}; the shared packet then holds "
              f"{default['shared_packet_passages']} passages, "
              f"{default['shared_packet_est_tokens']:,} est. tokens, with "
              f"{default['gold_fact_in_payload']['lean-shared']} of the 4 gold facts.", "",
              DOCS_END]
    return "\n".join(lines)


def rules_for(args) -> "tuple[str, str]":
    if args.standin:
        return standin_rules(), f"synthetic {STANDIN_LINES}-line stand-in"
    if args.rules:
        return Path(args.rules).read_text(encoding="utf-8"), args.rules
    if TEMPLATE_RULES.is_file():
        return TEMPLATE_RULES.read_text(encoding="utf-8"), "templates/vault/CLAUDE.md"
    return standin_rules(), f"synthetic {STANDIN_LINES}-line stand-in"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--rules", default=None,
                        help="Rule file a naive worker autoloads (default: "
                             "templates/vault/CLAUDE.md if present, else a 250-line stand-in).")
    parser.add_argument("--standin", action="store_true",
                        help=f"Use the synthetic {STANDIN_LINES}-line stand-in rule file.")
    parser.add_argument("--sample", type=int, default=2, help="Records sampled per worker.")
    parser.add_argument("--packet", choices=["compact", "default"], default="compact",
                        help="compact: budget-sized compact synaptic packets (the documented "
                             "setup, default); default: the fts packet plus link-graph extras.")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--docs", action="store_true",
                        help="Print the generated block of docs/subagents.md §5 (runs the "
                             "stand-in and the template rule file with compact packets).")
    args = parser.parse_args(argv)
    if args.docs:
        standin = run(standin_rules(), f"synthetic {STANDIN_LINES}-line stand-in", args.sample)
        template = run(TEMPLATE_RULES.read_text(encoding="utf-8"),
                       "templates/vault/CLAUDE.md", args.sample)
        default = run(standin_rules(), f"synthetic {STANDIN_LINES}-line stand-in",
                      args.sample, "default")
        print(docs_block(standin, template, default))
        return 0
    rules_text, label = rules_for(args)
    result = run(rules_text, label, args.sample, args.packet)
    if args.json:
        print(json.dumps(result, indent=1))
        return 0
    print(f"rules: {result['rules']} ({result['rules_lines']} lines, "
          f"{result['rules_est_tokens']:,} est. tokens); vault: {result['vault_notes']} "
          f"fictional notes; {result['packets']} synaptic packets; shared packet: "
          f"{result['shared_packet_passages']} passages, "
          f"{result['shared_packet_est_tokens']:,} est. tokens")
    print()
    print(table(result))
    print()
    print(f"planted fabricated records: {result['fabricated_records_planted']}; records "
          f"failing `handback check`: {result['records_failing_check']}")
    print("Estimated payload tokens (ceil(chars/4)) on a synthetic setup; not billed host "
          "tokens and not evidence about answer quality.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
