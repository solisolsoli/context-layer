def _utc() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _new_id() -> str:
    return datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "-" + secrets.token_hex(3)


def _host() -> str:
    """This machine, as a hash: enough to tell "same host", without a machine name on disk."""
    return "sha256:" + hashlib.sha256(platform.node().encode("utf-8")).hexdigest()[:16]


def _vault(value: str) -> Path:
    vault = Path(value).expanduser().resolve()
    if not vault.is_dir():
        raise TaskError(f"vault not found: {orchestrate.shown(None, vault)}")
    return vault


def _tail(path: Path) -> str:
    """A file named from its `.context` folder on, never with the home path in front."""
    parts = Path(path).parts
    if orchestrate.verbose() or ".context" not in parts:
        return str(path) if orchestrate.verbose() else Path(path).name
    return "/".join(parts[parts.index(".context"):])


def _reason(exc: BaseException) -> str:
    """An exception as a message that carries no absolute path."""
    if isinstance(exc, OSError) and exc.strerror:
        return exc.strerror
    return str(exc)


def _redact(value, vault: Path):
    """Printed JSON without absolute paths: the vault becomes <vault>, the home ~."""
    if orchestrate.verbose():
        return value
    if isinstance(value, str):
        return value.replace(str(vault), "<vault>").replace(str(Path.home()), "~")
    if isinstance(value, list):
        return [_redact(item, vault) for item in value]
    if isinstance(value, dict):
        return {key: _redact(item, vault) for key, item in value.items()}
    return value


def _tasks_root(vault: Path) -> Path:
    return vault / TASKS_DIR


def _task_dir(vault: Path, task_id: str) -> Path:
    if not task_id or "/" in task_id or task_id in (".", "..") or task_id.startswith("."):
        raise TaskError(f"not a task id: {task_id}")
    directory = _tasks_root(vault) / task_id
    if not (directory / "task.json").is_file():
        raise TaskError(f"no such task: {task_id}")
    return directory


def _read_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise TaskError(f"cannot read {_tail(path)}: {_reason(exc)}") from exc


def _write_json(path: Path, payload: dict) -> None:
    orchestrate.atomic_write(path, json.dumps(payload, indent=2, ensure_ascii=False) + "\n")


def _create_exclusive(path: Path, text: str) -> bool:
    """Create `path` holding `text` only if nothing is there yet (see orchestrate)."""
    return orchestrate.create_exclusive(path, text)


def _cancel_flag(directory: Path) -> Path:
    return directory / "cancel"


def _sha256_nofollow(path) -> str:
    """SHA-256 of a regular file opened without following a symlink swapped in meanwhile."""
    descriptor = os.open(str(path), os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
    digest = hashlib.sha256()
    with os.fdopen(descriptor, "rb") as handle:
        for block in iter(lambda: handle.read(65536), b""):
            digest.update(block)
    return digest.hexdigest()


def _fold(name: str) -> str:
    """How a case-insensitive, normalising disk compares names (as source_policy does)."""
    return unicodedata.normalize("NFC", unicodedata.normalize("NFC", name).casefold())


def _overlap(first: str, second: str) -> bool:
    """Equal, or one contains the other, compared case- and NFC-folded."""
    first, second = _fold(first).rstrip("/"), _fold(second).rstrip("/")
    return first == second or first.startswith(second + "/") or second.startswith(first + "/")


@contextmanager
def _registry_lock(vault: Path):
    """One writer at a time for the task registry: new tasks, leases, recoveries."""
    root = _tasks_root(vault)
    root.mkdir(parents=True, exist_ok=True)
    with file_lock(root / ".lock"):
        yield


