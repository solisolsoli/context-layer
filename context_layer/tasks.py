def cmd_verify(args: argparse.Namespace) -> int:
    vault, task_id = _target(args)
    directory = _task_dir(vault, task_id)
    result = _read_json(directory / "result.json")
    if result.get("state") != "pending_review":
        print(f"context-layer tasks verify: {task_id} is {result.get('state')}; only a "
              "pending_review task can be verified", file=sys.stderr)
        return 2
    verification = _verification(vault, directory, task_id, result)
    try:
        verification["ledger"] = orchestrate.ledger_append(
            vault, _ledger_event(vault, task_id, directory, verification))
    except orchestrate.OrchestrateError as exc:
        raise TaskError(f"the verdict was not recorded: {exc}") from exc
    if args.record:
        task = _pinned(vault, directory, task_id)[0] or _read_json(directory / "task.json")
        verification["memory"] = _record_memory(vault, task,
                                                _read_json(directory / "packet.json"),
                                                verification)
        if verification["memory"].get("recorded"):
            orchestrate.ledger_append(vault, {
                "event": "record", "task_id": task_id,
                "memory_id": verification["memory"].get("id"),
                "cites": verification["ledger"]["sha256"],
                "verdict": verification["state"]})
    check = verification.pop("check", None)
    if check:
        verification["check_sha256"] = orchestrate.check_digest(check)
    result["verification"] = verification
    _finish(vault, task_id, result, verification["state"],
            "; ".join(verification["problems"]) if verification["problems"]
            else "verified by the coordinator")
    if args.json:
        print(json.dumps(_redact({"id": task_id, **verification}, vault), indent=2,
                         ensure_ascii=False))
    else:
        print(f"{task_id}  {verification['state']}")
        for problem in verification["problems"]:
            print(f"  problem  {_redact(problem, vault)}")
        for item in verification["outputs"]:
            print(f"  output   {item['path']}  {item['sha256']}")
        for note in verification["notes"]:
            print(f"  note     {_redact(note, vault)}")
        print(f"  ledger   line {verification['ledger']['n']} "
              f"sha256 {verification['ledger']['sha256']}")
        if verification["memory"]:
            print(f"  memory   {verification['memory']['note']}")
    return 0 if verification["state"] == "verified" else 1


def _interrupted_attempt(directory: Path, runner: dict, backend: str) -> dict | None:
    """What is known of the attempt a dead runner left behind, so it is still counted."""
    number = runner.get("attempt")
    if not isinstance(number, int) or (directory / "attempts" / f"{number}.json").exists():
        return None
    text, _ = _stdout_text(directory / "attempts" / f"{number}.stdout")
    parsed = backends.parse_output(text, backend=backend)
    return {"attempt": number, "backend": backend, "interrupted": True, "ok": False,
            "failure": "the runner stopped during this attempt", "exit_code": None,
            "cancelled": False, "timed_out": False, "wall_s": None,
            "usage": parsed["usage"], "model_usage": parsed["model_usage"],
            "total_cost_usd": parsed["total_cost_usd"], "is_error": parsed["is_error"],
            "notes": ["recorded by recovery from the attempt's stdout; its cost may be "
                      "incomplete"] + parsed["notes"],
            "unauthorized_changes": [], "definition_problems": [], "output_problems": [],
            "stdout": f"{number}.stdout", "stderr": f"{number}.stderr"}


def _recover_one(vault: Path, directory: Path, task_id: str, runner: dict, final: str,
                 why: str) -> str:
    """Stop a dead runner's child group, count its attempt, end the task in `final`."""
    stopped = _stop_group(runner.get("child_pgid"))
    result = _read_json(directory / "result.json")
    task = _read_json(directory / "task.json")
    attempt = _interrupted_attempt(directory, runner, task.get("backend", "?"))
    if attempt:
        result.setdefault("attempts", []).append(attempt)
    reason = (f"{why}; runner pid {runner.get('runner_pid')} is not running; {stopped}")
    _finish(vault, task_id, result, final, reason)
    runner.update({"ended_at": _utc(), "child_pgid": None, "recovered_at": _utc(),
                   "recovered_by_pid": os.getpid(), "final_state": final})
    _write_json(directory / RUNNER_NAME, runner)
    for lease in _lease_dir(vault).glob("*.json"):
        try:
            held = json.loads(lease.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if isinstance(held, dict) and held.get("task_id") == task_id \
                and not _alive(held.get("runner_pid")):
            lease.unlink(missing_ok=True)
    return reason


def cmd_cancel(args: argparse.Namespace) -> int:
    vault, task_id = _target(args)
    directory = _task_dir(vault, task_id)
    result = _read_json(directory / "result.json")
    state = result.get("state")
    if state not in ("queued", "running"):
        print(f"context-layer tasks cancel: {task_id} is {state}; only a queued or running "
              "task can be cancelled", file=sys.stderr)
        return 2
    orchestrate.atomic_write(_cancel_flag(directory), _utc() + "\n")
    if state == "queued":
        claim = _claim(directory, task_id, purpose="cancel")
        if claim is not None:
            result = _read_json(directory / "result.json")
            if result.get("state") == "queued":
                _finish(vault, task_id, result, "cancelled", "cancelled before it ran")
                _Beat(directory, claim).end("cancelled")
                print(f"{task_id}  cancelled")
                return 0
    runner = _read_runner(directory)
    if runner is None:
        print(f"{task_id}  cancel requested; no runner has claimed it yet")
        return 0
    if runner.get("host") != _host():
        print(f"{task_id}  cancel requested; its runner is on another host and cannot be "
              "checked from here")
        return 0
    if _alive(runner.get("runner_pid")):
        print(f"{task_id}  cancel requested; runner pid {runner.get('runner_pid')} stops the "
              "child and records cancelled")
        return 0
    with _registry_lock(vault):
        reason = _recover_one(vault, directory, task_id, runner, "cancelled",
                              "cancelled by `tasks cancel`")
    print(f"{task_id}  cancelled ({reason})")
    return 0


def cmd_recover(args: argparse.Namespace) -> int:
    vault = _vault(args.vault)
    ids = list(dict.fromkeys(args.ids))
    if ids:
        for task_id in ids:
            _task_dir(vault, task_id)
    else:
        ids = [task["id"] for task, result in _all_tasks(vault)
               if result.get("state") in ("queued", "running")]
    report = []
    for task_id in ids:
        directory = _task_dir(vault, task_id)
        with _registry_lock(vault):
            result = _read_json(directory / "result.json")
            state = result.get("state")
            runner = _read_runner(directory)
            final = "cancelled" if _cancel_flag(directory).exists() else "failed"
            if state not in ("queued", "running"):
                outcome = ("left", f"state {state}; nothing to recover")
            elif runner is None:
                outcome = ("left", "no runner has claimed it" if state == "queued" else
                           "no runner record (a run started before 0.4?); nothing was "
                           "checked or stopped")
            elif runner.get("ended_at"):
                outcome = (final, _recover_one(vault, directory, task_id, runner, final,
                                               "its runner ended without finishing it"))
            elif runner.get("host") != _host():
                outcome = ("left", "its runner is on another host; liveness cannot be "
                                   "checked from here")
            elif _alive(runner.get("runner_pid")):
                outcome = ("left", f"runner pid {runner.get('runner_pid')} is alive "
                                   f"(heartbeat {runner.get('heartbeat_at')})")
            else:
                outcome = (final, _recover_one(vault, directory, task_id, runner, final,
                                               "recovered by `tasks recover`"))
        report.append({"id": task_id, "outcome": outcome[0], "detail": outcome[1]})
    if args.json:
        print(json.dumps(_redact(report, vault), indent=2, ensure_ascii=False))
    elif not report:
        print("no queued or running task to check")
    for item in ([] if args.json else report):
        print(f"{item['id']}  {item['outcome']}  {item['detail']}")
    return 0


def cmd_ledger(args: argparse.Namespace) -> int:
    vault = _vault(args.vault)
    entries, problems = orchestrate.read_ledger(vault)
    head = entries[-1] if entries else None
    events: dict = {}
    for entry in entries:
        kind = entry["record"].get("event")
        events[kind] = events.get(kind, 0) + 1
    replay: list = []
    if args.replay:
        latest, _ = _attestations(vault)
        for task_id, entry in sorted(latest.items()):
            record = entry["record"]
            try:
                directory = _task_dir(vault, task_id)
                result = _read_json(directory / "result.json")
                again = _verification(vault, directory, task_id, result)
            except TaskError as exc:
                replay.append({"id": task_id, "line": entry["n"], "reproduced": False,
                               "detail": str(exc)})
                continue
            produced = [{"path": item["path"], "sha256": item["sha256"]}
                        for item in again["outputs"]]
            differs = []
            if again["state"] != record.get("verdict"):
                differs.append(f"verdict now {again['state']}, ledger {record.get('verdict')}")
            if produced != record.get("produced"):
                differs.append("produced files differ")
            if _pin_definition(vault, task_id) != record.get("definition_sha256"):
                differs.append("task definition differs")
            replay.append({"id": task_id, "line": entry["n"], "reproduced": not differs,
                           "detail": "; ".join(differs) or "same verdict from the same bytes"})
    # The hash chain alone cannot see an edit of the head line (nothing chains to it), or a
    # cut tail. Each attested task's result.json cites the ledger line of its verdict, so
    # the chain is also checked against those citations.
    unattested: list = []
    if not problems:
        latest, _ = _attestations(vault)
        rows_problems: list = []
        for task, result in _all_tasks(vault, rows_problems):
            why = _unattested(task["id"], result, latest, [])
            if why:
                unattested.append({"id": task["id"], "state": result.get("state"), "why": why})
    summary = {"ledger": LEDGER_SHOWN, "lines": len(entries), "events": events,
               "head": {"n": head["n"], "sha256": head["sha256"]} if head else None,
               "chain": "ok" if not problems else "broken", "problems": problems,
               "unattested": unattested, "replay": replay if args.replay else None}
    if args.json:
        print(json.dumps(summary, indent=2, ensure_ascii=False))
    else:
        print(f"ledger {LEDGER_SHOWN}: {len(entries)} line(s) "
              + (", ".join(f"{kind} {count}" for kind, count in sorted(events.items()))
                 if events else "") + f"; chain {summary['chain']}")
        for problem in problems:
            print(f"  problem  {problem}")
        for item in unattested:
            print(f"  problem  task {item['id']} ({item['state']}) is not backed by the ledger: "
                  f"{item['why']}")
        if head:
            print(f"  head     line {head['n']} sha256 {head['sha256']}")
        for item in replay:
            print(f"  replay   {item['id']} (line {item['line']}): "
                  f"{'reproduced' if item['reproduced'] else 'DIFFERS'}; {item['detail']}")
    failed = problems or unattested or any(not item["reproduced"] for item in replay)
    return 1 if failed else 0


LEDGER_SHOWN = orchestrate.LEDGER_NAME


def _coordinator_usage(path: Path) -> dict:
    """The host's own usage JSON, so a total covers coordinator + agents + retries.

    Every number is validated: a counter or a cost that is not a finite,
    non-negative number is an error here (the user supplied the file), while an
    entry with no token counts at all is counted as usage unknown, never as zero.
    """
    payload = _read_json(path)
    entries = payload if isinstance(payload, list) else [payload]
    attempts: list = []
    for number, entry in enumerate(entries, start=1):
        if not isinstance(entry, dict):
            raise TaskError(f"{path.name}: every entry must be a JSON object")
        label = f"{path.name} entry {number}"
        source = entry.get("usage") if isinstance(entry.get("usage"), dict) else entry
        present = [key for key in backends.USAGE_KEYS if source.get(key) is not None]
        usage = None
        if present:
            usage, why = backends.check_usage(source)
            if usage is None:
                raise TaskError(f"{label}: {why}")
        cost = entry.get("total_cost_usd")
        if cost is not None and backends.amount(cost) is None:
            raise TaskError(f"{label}: total_cost_usd must be a finite, non-negative number "
                            f"({cost!r})")
        wall = entry.get("wall_s")
        if wall is not None and backends.amount(wall) is None:
            raise TaskError(f"{label}: wall_s must be a finite, non-negative number ({wall!r})")
        if wall is None and entry.get("duration_ms") is not None:
            duration = backends.amount(entry["duration_ms"])
            if duration is None:
                raise TaskError(f"{label}: duration_ms must be a finite, non-negative number "
                                f"({entry['duration_ms']!r})")
            wall = duration / 1000.0
        model_usage, notes = backends.check_model_usage(entry.get("modelUsage"))
        if notes:
            raise TaskError(f"{label}: {notes[0]}")
        attempts.append({"usage": usage, "total_cost_usd": cost, "wall_s": wall or 0.0,
                         "model_usage": model_usage})
    return _totals(attempts)


def _print_totals(label: str, totals: dict) -> None:
    usage = totals["usage"]
    print(f"{label:<24} {totals['attempts']:>4} {usage['input_tokens']:>9} "
          f"{usage['output_tokens']:>9} {usage['cache_creation_input_tokens']:>9} "
          f"{usage['cache_read_input_tokens']:>9} {totals['total_cost_usd']:>12.6f} "
          f"{totals['wall_s']:>9.3f}")


def _merge(first: dict, second: dict) -> dict:
    models = {model: dict(entry) for model, entry in first["model_usage"].items()}
    for model, entry in second["model_usage"].items():
        total = models.setdefault(model, {key: 0 for key in backends.MODEL_USAGE_KEYS})
        for key in backends.MODEL_USAGE_KEYS:
            total[key] = total.get(key, 0) + entry.get(key, 0)
        if "costUSD" in entry:
            total["costUSD"] = round(total.get("costUSD", 0.0) + entry["costUSD"], 6)
    return {"attempts": first["attempts"] + second["attempts"],
            "usage": {key: first["usage"][key] + second["usage"][key]
                      for key in backends.USAGE_KEYS},
            "total_cost_usd": round(first["total_cost_usd"] + second["total_cost_usd"], 6),
            "wall_s": round(first["wall_s"] + second["wall_s"], 3),
            "usage_unknown": first["usage_unknown"] + second["usage_unknown"],
            "cost_unknown": first["cost_unknown"] + second["cost_unknown"],
            "model_usage": models}


def cmd_cost(args: argparse.Namespace) -> int:
    vault = _vault(args.vault)
    problems: list = []
    rows = _all_tasks(vault, problems)
    if args.id:
        rows = [(task, result) for task, result in rows if task["id"] == args.id]
        problems = [item for item in problems if item[0] == args.id]
        if not rows and not problems:
            raise TaskError(f"no such task: {args.id}")
    _warn_unreadable(problems)
    per_task = [(task["id"], _totals(result.get("attempts", []))) for task, result in rows]
    grand = _totals([attempt for _, result in rows for attempt in result.get("attempts", [])])
    coordinator = None
    if args.coordinator_usage:
        coordinator = _coordinator_usage(Path(args.coordinator_usage).expanduser())
        merged = _merge(grand, coordinator)
    else:
        merged = grand
    labels = {"cost": backends.COST_LABEL, "usage": backends.USAGE_LABEL}
    if args.json:
        print(json.dumps({"tasks": [{"id": task_id, **totals} for task_id, totals in per_task],
                          "agents": grand, "coordinator": coordinator, "total": merged,
                          "labels": labels,
                          "unreadable_tasks": [name for name, _ in problems]},
                         indent=2, ensure_ascii=False))
        return 1 if problems else 0
    print(f"{'task':<24} {'att':>4} {'in':>9} {'out':>9} {'cache_w':>9} {'cache_r':>9} "
          f"{'host_est_usd':>12} {'wall_s':>9}")
    for task_id, totals in per_task:
        _print_totals(task_id, totals)
    if coordinator:
        _print_totals("coordinator", coordinator)
    _print_totals("TOTAL", merged)
    if merged["usage_unknown"]:
        print(f"{merged['usage_unknown']} attempt(s) reported no usage; their tokens are "
              "missing from this total.")
    if merged["cost_unknown"]:
        print(f"{merged['cost_unknown']} attempt(s) reported no usable cost; their spend is "
              "missing from this total.")
    if merged["model_usage"]:
        print("modelUsage (every model call the host counted, subagents included):")
        for model, entry in sorted(merged["model_usage"].items()):
            print(f"  {model:<32} in {entry['inputTokens']} out {entry['outputTokens']} "
                  f"cache_r {entry['cacheReadInputTokens']} "
                  f"cache_w {entry['cacheCreationInputTokens']}"
                  + (f" est_usd {entry['costUSD']:.6f}" if "costUSD" in entry else ""))
    print(f"Cost is {labels['cost']}. Token columns: {labels['usage']}.")
    if problems:
        print(f"{len(problems)} task(s) could not be read; this total leaves them out.",
              file=sys.stderr)
        return 1
    return 0


