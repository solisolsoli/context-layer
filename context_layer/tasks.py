def _identity(vault: Path, relative: str) -> list:
    """[name, st_dev, st_ino] (lstat) of the vault folder and every component of `relative`."""
    chain: list = []
    current = vault
    for name in (".", *PurePosixPath(relative).parts):
        if name != ".":
            current = current / name
        info = os.lstat(current)
        if not stat.S_ISDIR(info.st_mode):
            raise TaskError(f"output directory component is not a real directory: {name}")
        chain.append([name, info.st_dev, info.st_ino])
    return chain


def _identity_problems(vault: Path, relative: str, recorded) -> list:
    """Why the output directory is no longer the one recorded at dispatch, if it is not."""
    names = [".", *PurePosixPath(relative).parts]
    if not isinstance(recorded, list) or not recorded:
        return ["no output-directory identity was recorded at dispatch (a task created "
                "before 0.4); re-create the task"]
    if [entry[0] if isinstance(entry, list) and len(entry) == 3 else None
            for entry in recorded] != names:
        return ["the recorded output-directory identity does not name the pinned output "
                "directory"]
    current = vault
    walked: list = []
    for name, device, inode in recorded:
        if name != ".":
            current = current / name
            walked.append(name)
        label = "/".join(walked) or "the vault folder"
        try:
            info = os.lstat(current)
        except FileNotFoundError:
            return [f"output directory replaced: {label} no longer exists"]
        except OSError as exc:
            return [f"output directory cannot be checked: {label} ({_reason(exc)})"]
        if stat.S_ISLNK(info.st_mode):
            return [f"output directory replaced: {label} is now a symlink"]
        if not stat.S_ISDIR(info.st_mode):
            return [f"output directory replaced: {label} is no longer a directory"]
        if (info.st_dev, info.st_ino) != (device, inode):
            return [f"output directory replaced: {label} is not the directory recorded at "
                    "dispatch"]
    return []


def _walk_output(vault: Path, relative: str) -> tuple:
    """({path: SHA-256} for every regular file under the output directory, problems).

    Nothing is followed. A symlink (to a file or a directory), a file with more
    than one hard link, and anything that is neither a regular file nor a
    directory is a problem: each can make existing vault bytes pass for output.
    """
    top = vault / relative
    files: dict = {}
    problems: list = []
    try:
        info = os.lstat(top)
    except FileNotFoundError:
        return files, [f"output directory is missing: {relative}"]
    if stat.S_ISLNK(info.st_mode):
        return files, [f"output directory replaced: {relative} is now a symlink"]
    if not stat.S_ISDIR(info.st_mode):
        return files, [f"output directory replaced: {relative} is no longer a directory"]
    pending = [top]
    while pending:
        directory = pending.pop()
        try:
            entries = sorted(os.scandir(directory), key=lambda entry: entry.name)
        except OSError as exc:
            problems.append(f"unreadable output directory: "
                            f"{Path(directory).relative_to(vault).as_posix()} ({_reason(exc)})")
            continue
        for entry in entries:
            name = Path(entry.path).relative_to(vault).as_posix()
            try:
                info = entry.stat(follow_symlinks=False)
            except OSError as exc:
                problems.append(f"unreadable output: {name} ({_reason(exc)})")
                continue
            if stat.S_ISLNK(info.st_mode):
                problems.append(f"symlink in output: {name}")
            elif stat.S_ISDIR(info.st_mode):
                pending.append(Path(entry.path))
            elif not stat.S_ISREG(info.st_mode):
                problems.append(f"not a regular file in output: {name}")
            elif info.st_nlink > 1:
                problems.append(f"hard-linked output: {name} ({info.st_nlink} links: its bytes "
                                "are shared with another file)")
            else:
                try:
                    files[name] = _sha256_nofollow(entry.path)
                except OSError as exc:
                    problems.append(f"unreadable output: {name} ({_reason(exc)})")
    return dict(sorted(files.items())), problems


def _snapshot(vault: Path, out_relative: str) -> dict:
    """path -> SHA-256 of every regular file under the output directory (see _walk_output)."""
    return _walk_output(vault, out_relative)[0]


def _produced(baseline: dict, after: dict) -> list:
    """Files created or modified in the output directory since the run began."""
    found: list = []
    for relative in sorted(after):
        if baseline.get(relative) == after[relative]:
            continue
        found.append({"path": relative, "fingerprint": after[relative],
                      "change": "modified" if relative in baseline else "created"})
    return found


