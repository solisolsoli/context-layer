def _workspace(vault: Path, directory: Path) -> Path:
    """A fresh private directory outside the vault holding copies of prompt and packet."""
    workspace = private_tempdir(prefix="context-layer-task-").resolve()
    if workspace.is_relative_to(vault):
        shutil.rmtree(workspace, ignore_errors=True)
        raise OSError(0, "the temporary workspace would sit inside the vault; point TMPDIR "
                         "outside it")
    for name in ("prompt.txt", "packet.json"):
        shutil.copyfile(directory / name, workspace / name)
    return workspace


def _stdout_text(path: Path) -> tuple:
    """(stdout text, note) with at most STDOUT_PARSE_CAP bytes read, from the end."""
    try:
        size = path.stat().st_size
    except OSError:
        return "", None
    with open(path, "rb") as handle:
        if size > STDOUT_PARSE_CAP:
            handle.seek(size - STDOUT_PARSE_CAP)
        data = handle.read(STDOUT_PARSE_CAP)
    note = (f"stdout is {size} bytes; only its last {STDOUT_PARSE_CAP} were parsed"
            if size > STDOUT_PARSE_CAP else None)
    return data.decode("utf-8", errors="replace"), note


def _attempt(vault: Path, directory: Path, resolved, number: int, timeout_s: float,
             out_abs: Path, beat: _Beat) -> dict:
    """One costed run of the backend. stdout/stderr go straight to files, never a pipe."""
    attempts = directory / "attempts"
    attempts.mkdir(parents=True, exist_ok=True)
    stdout_path = attempts / f"{number}.stdout"
    stderr_path = attempts / f"{number}.stderr"
    record = {"attempt": number, "backend": resolved.backend, "argv": list(resolved.argv),
              "started_at": _utc(), "notes": list(resolved.notes), "spawn_error": None,
              "workspace": "temporary, outside the vault" if resolved.isolated
              else "the task directory", "child_pgid": None}
    child_env = dict(os.environ)
    child_env["CONTEXT_LAYER_OUT_DIR"] = str(out_abs)
    exit_code = None
    cancelled = False
    timed_out = False
    workspace = None
    started = time.monotonic()
    try:
        cwd = directory
        if resolved.isolated:
            workspace = _workspace(vault, directory)
            cwd = workspace
        child_env["CONTEXT_LAYER_TASK_DIR"] = str(cwd)
        with open(stdout_path, "wb") as out_handle, open(stderr_path, "wb") as err_handle:
            stdin_handle = open(directory / "prompt.txt", "rb") \
                if resolved.stdin == "prompt" else None
            try:
                with managed_process_tree(
                    list(resolved.argv), cwd=str(cwd),
                    stdin=stdin_handle if stdin_handle else subprocess.DEVNULL,
                    stdout=out_handle, stderr=err_handle, env=child_env,
                ) as process:
                    record["child_pgid"] = process.pid
                    beat(attempt=number, child_pgid=process.pid)
                    while True:
                        try:
                            exit_code = process.wait(timeout=POLL_S)
                            break
                        except subprocess.TimeoutExpired:
                            pass
                        beat()
                        if _cancel_flag(directory).exists():
                            cancelled = True
                        elif timeout_s and (time.monotonic() - started) > timeout_s:
                            timed_out = True
                        if cancelled or timed_out:
                            _kill(process)
                            exit_code = process.poll()
                            break
            finally:
                if stdin_handle:
                    stdin_handle.close()
    except OSError as exc:
        record["spawn_error"] = _reason(exc)
    finally:
        if workspace is not None:
            shutil.rmtree(workspace, ignore_errors=True)
        beat(child_pgid=None)
    record["wall_s"] = round(time.monotonic() - started, 3)
    record["ended_at"] = _utc()
    record["exit_code"] = exit_code
    record["timed_out"] = timed_out
    record["cancelled"] = cancelled
    text, note = _stdout_text(stdout_path)
    if note:
        record["notes"].append(note)
    parsed = backends.parse_output(text, backend=resolved.backend)
    for key in ("parsed", "is_error", "subtype", "usage", "usage_raw", "model_usage",
                "total_cost_usd", "duration_ms", "num_turns"):
        record[key] = parsed[key]
    record["notes"] += parsed["notes"]
    record["result_text"] = parsed["result"][:RESULT_TEXT_LIMIT]
    record["result_truncated"] = len(parsed["result"]) > RESULT_TEXT_LIMIT
    record["stdout"] = stdout_path.name
    record["stderr"] = stderr_path.name
    record["retry"] = True
    if record["spawn_error"]:
        failure = f"backend did not start: {record['spawn_error']}"
    elif cancelled:
        failure = "cancelled"
    elif timed_out:
        failure = f"timed out after {timeout_s:g}s"
    elif parsed["no_retry"]:
        failure = f"the backend stopped on its own limit ({parsed['subtype']})"
        record["retry"] = False
    elif exit_code != 0:
        failure = f"exit code {exit_code}"
    elif parsed["is_error"]:
        failure = "backend reported is_error" + (f" ({parsed['subtype']})"
                                                 if parsed["subtype"] else "")
    else:
        failure = None
    record["failure"] = failure
    record["ok"] = failure is None
    return record


class _RunState:
    """What the tasks of one `tasks run` process share: their output directories."""

    def __init__(self):
        self.lock = threading.Lock()
        self.dirs: dict = {}

    def add(self, task_id: str, out_relative: str) -> None:
        with self.lock:
            self.dirs[task_id] = out_relative

    def others(self, task_id: str) -> dict:
        with self.lock:
            return {key: value for key, value in self.dirs.items() if key != task_id}


def _skipped(task_id: str, why: str) -> dict:
    return {"id": task_id, "skipped": why}


def _run_one(vault: Path, task_id: str, run: _RunState | None = None) -> dict:
    """queued -> running -> pending_review | failed | blocked | cancelled.

    Returns {"skipped": why} instead when another runner holds the task or its
    output directory, or when the task is no longer queued.
    """
    run = run or _RunState()
    directory = _task_dir(vault, task_id)
    result = _read_json(directory / "result.json")
    if result.get("state") != "queued":
        return _skipped(task_id, f"state {result.get('state')}")
    task, tampered = _pinned(vault, directory, task_id)
    if tampered:
        claim = _claim(directory, task_id)
        if claim is None:
            return _skipped(task_id, _holder(directory))
        beat = _Beat(directory, claim)
        done = _finish(vault, task_id, result, "blocked", "; ".join(tampered))
        beat.end(done["state"])
        return done
    lease, why = _acquire_lease(vault, task_id, task["output_dir"])
    if lease is None:
        return _skipped(task_id, why)
    try:
        claim = _claim(directory, task_id)
        if claim is None:
            return _skipped(task_id, _holder(directory))
        beat = _Beat(directory, claim)
        done = None
        try:
            result = _read_json(directory / "result.json")   # re-read after the claim
            if result.get("state") != "queued":
                return _skipped(task_id, f"state {result.get('state')}")
            run.add(task_id, task["output_dir"])
            done = _execute(vault, directory, task_id, task, result, beat, run)
            return done
        finally:
            beat.end(done.get("state") if isinstance(done, dict) else None)
    finally:
        _release_lease(lease)


def _holder(directory: Path) -> str:
    holder = _read_runner(directory) or {}
    return (f"claimed by runner pid {holder.get('runner_pid')} "
            f"({holder.get('purpose', 'run')}) at {holder.get('started_at')}")


def _execute(vault: Path, directory: Path, task_id: str, task: dict, result: dict,
             beat: _Beat, run: _RunState) -> dict:
    try:
        out_relative = task["output_dir"]
        out_abs = vault / out_relative
        prompt_file = directory / "prompt.txt"
        cap = task.get("max_cost_usd")
        try:
            resolved = _plan(task, prompt_file, out_abs, cap)
        except backends.BackendError as exc:
            return _finish(vault, task_id, result, "blocked", str(exc))
        absent = backends.missing_binary(resolved)
        if absent:
            return _finish(vault, task_id, result, "blocked",
                           f"backend binary not found on PATH: {absent}")
        if _cancel_flag(directory).exists():
            return _finish(vault, task_id, result, "cancelled",
                           "cancelled before the first attempt")
        replaced = _identity_problems(vault, out_relative, task.get("output_identity"))
        if replaced:
            return _finish(vault, task_id, result, "blocked", "; ".join(replaced))
        # What the output directory held before any attempt ran. Only files
        # created or modified against this baseline count as the run's output,
        # so a pre-existing vault file can never be passed off as a result.
        # Kept in memory and written by the runner after each attempt, which
        # overwrites anything the backend wrote into result.json meanwhile.
        baseline, problems = _walk_output(vault, out_relative)
        if problems:
            return _finish(vault, task_id, result, "blocked", "; ".join(problems))
        result["state"] = "running"
        result["started_at"] = _utc()
        result["command"] = list(resolved.argv)
        result["backend_notes"] = list(resolved.notes)
        result["runner"] = {"runner_pid": os.getpid(), "host": _host()}
        result["output_baseline"] = baseline
        result["produced"] = []
        result["removed_from_output"] = []
        _save(vault, task_id, result)

        state = "failed"
        reason = "no attempt ran"
        started = time.monotonic()
        spent = 0.0
        tokens = 0
        for number in range(1, int(task["max_attempts"]) + 1):
            if _cancel_flag(directory).exists():
                state, reason = "cancelled", f"cancelled before attempt {number}"
                break
            timeout = float(task["timeout_s"])
            limit = task.get("max_elapsed_s")
            if limit:
                remaining = float(limit) - (time.monotonic() - started)
                if remaining <= 0:
                    reason += f"; the job's {limit}s time limit is spent"
                    break
                timeout = min(timeout, remaining)
            if cap is not None:
                if cap - spent <= 0:
                    reason += f"; the {cap:g} USD spend cap (host-estimated) is spent"
                    break
                resolved = _plan(task, prompt_file, out_abs, cap - spent)
            before = _manifest(vault)
            attempt = _attempt(vault, directory, resolved, number, timeout, out_abs, beat)
            after = _manifest(vault)
            unauthorized, concurrent, appends = _classify(before, after, out_relative,
                                                          run.others(task_id), vault)
            attempt["unauthorized_changes"] = unauthorized
            attempt["concurrent_task_writes"] = concurrent
            attempt["memory_appends"] = appends
            _, tampered = _pinned(vault, directory, task_id)
            attempt["definition_problems"] = tampered
            files, walk_problems = _walk_output(vault, out_relative)
            attempt["output_problems"] = _identity_problems(
                vault, out_relative, task.get("output_identity")) + walk_problems
            result["produced"] = _produced(baseline, files)
            result["removed_from_output"] = sorted(set(baseline) - set(files))
            text = json.dumps(attempt, indent=2, ensure_ascii=False) + "\n"
            if not _create_exclusive(directory / "attempts" / f"{number}.json", text):
                attempt["notes"].append(f"attempts/{number}.json already existed and was "
                                        "left as it was")
            result["attempts"].append(attempt)
            _save(vault, task_id, result)
            spent += backends.amount(attempt.get("total_cost_usd")) or 0.0
            counts = backends.normalise_usage(attempt.get("usage"))
            tokens += sum(counts.values()) if counts else 0
            if attempt["cancelled"]:
                state, reason = "cancelled", f"cancelled during attempt {number}"
                break
            if attempt["ok"]:
                state, reason = "pending_review", f"attempt {number} finished; not verified yet"
                break
            reason = f"attempt {number}: {attempt['failure']}"
            if attempt.get("retry") is False:
                reason += " (not retried: the same limit would stop it again)"
                break
            usage_cap = task.get("max_total_usage_tokens")
            if usage_cap and tokens >= usage_cap:
                reason += (f"; the job's usage cap of {usage_cap} tokens is reached (checked "
                           "between attempts, not enforced by the backend)")
                break
        return _finish(vault, task_id, result, state, reason)
    except (OSError, ValueError, KeyError, TypeError) as exc:
        return _finish(vault, task_id, result, "blocked", f"runner error: {_reason(exc)}")


