"""context_layer.tasks — bounded sub-agent tasks that a coordinator verifies.

Everything a task owns is a plain file inside the vault, so a person can read,
diff and delete it without this tool:

    .context/tasks/<task-id>/task.json    the spec, with the output directory's identity
                             packet.json   the evidence handed to the agent
                             prompt.txt    exactly what the agent was sent
                             runner.json   the claim: which runner ran it, its child, heartbeat
                             attempts/<n>.json  .stdout  .stderr
                             result.json   the state machine
                             out/          default allowed output directory
    .context/tasks/TASKS.md               derived Markdown mirror
    .context/tasks/LEDGER.jsonl           hash-chained verification ledger
    .context/tasks/.leases/               output-directory leases held during `run`
    .context/task-pins/<task-id>.json     dispatch pin (watched, see below)

This tool hands the agent the goal and a bounded evidence packet, not the
vault; the agent process still runs as the same user and can read and write
the vault unless its host stops it. A finished run is `pending_review`; only
`tasks verify` can say `verified`, and it rejects a result whose attempt wrote
outside the allowed output directory, whose task definition or output
directory changed after dispatch, or that created or modified no file there
during the run. Detection is a hash diff inside the vault, not a sandbox: a
write outside the vault, or a change undone before the attempt ends, is not
seen.

Python 3.10+; standard library only. No model call happens in this module.
"""

