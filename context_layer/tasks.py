def _outputs(vault: Path, out_relative: str) -> tuple:
    """Every regular file under the allowed output directory, hashed, without following."""
    files, problems = _walk_output(vault, out_relative)
    found = []
    for relative, digest in files.items():
        try:
            size = os.lstat(vault / relative).st_size
        except OSError as exc:
            problems.append(f"unreadable output: {relative} ({_reason(exc)})")
            continue
        found.append({"path": relative, "sha256": digest, "bytes": size})
    return found, problems


def _run_outputs(vault: Path, out_relative: str, produced) -> tuple:
    """The run's own outputs: produced during the run and unchanged since.

    `produced` is what the runner recorded against the pre-run baseline. A file
    that was already there and untouched never appears in it, and a produced
    file edited or removed after the run no longer matches its fingerprint.
    """
    current, problems = _outputs(vault, out_relative)
    if not isinstance(produced, list):
        return [], problems + ["no record of what the run produced (run before 0.3.0?)"]
    by_path = {item["path"]: item for item in current}
    outputs: list = []
    for entry in produced:
        if not isinstance(entry, dict) or not isinstance(entry.get("path"), str):
            problems.append("malformed produced-output record")
            continue
        relative = entry["path"]
        if not (relative == out_relative or relative.startswith(out_relative.rstrip("/") + "/")):
            problems.append(f"produced-output record outside {out_relative}: {relative}")
            continue
        now = by_path.get(relative)
        if now is None:
            problems.append(f"output missing since the run: {relative}")
            continue
        if now["sha256"] != entry.get("fingerprint"):
            problems.append(f"output changed after the run: {relative}")
            continue
        outputs.append({**now, "change": entry.get("change", "created")})
    return outputs, problems


def _verification(vault: Path, directory: Path, task_id: str, result: dict) -> dict:
    """The verdict on a pending_review task, computed from the files only (no writes).

    `tasks verify` records it; `tasks ledger --replay` recomputes it later and
    compares it with the ledger line.
    """
    task, problems = _pinned(vault, directory, task_id)
    notes: list = []
    check = None
    if task is None:  # No trustworthy definition: nothing else can be checked.
        task = {"id": task_id, "goal": "", "output_dir": "(unknown)"}
        outputs: list = []
    else:
        problems += _identity_problems(vault, task["output_dir"], task.get("output_identity"))
        outputs, output_problems = _run_outputs(vault, task["output_dir"],
                                                result.get("produced"))
        problems += output_problems
    unauthorized = result.get("unauthorized_changes", [])
    if unauthorized:
        problems.insert(0, "wrote outside " + task["output_dir"] + ": "
                        + ", ".join(f"{change['path']} ({change['change']})"
                                    for change in unauthorized))
    for attempt in result.get("attempts", []):
        for problem in (attempt.get("definition_problems") or []) \
                + (attempt.get("output_problems") or []):
            labelled = f"attempt {attempt.get('attempt')}: {problem}"
            if problem not in problems and labelled not in problems:
                problems.append(labelled)
    if not outputs and task["output_dir"] != "(unknown)":
        problems.append(f"no output file was created or modified under "
                        f"{task['output_dir']} during the run")
    if isinstance(task.get("job"), dict):
        handback, check = orchestrate.task_handback(vault, task)
        problems += handback
        problems += orchestrate.modified_source_problems(vault, outputs)
    removed = result.get("removed_from_output") or []
    if removed:
        notes.append("removed from the output directory during the run (present before it): "
                     + ", ".join(removed))
    concurrent = result.get("concurrent_task_writes") or []
    if concurrent:
        owners = sorted({str(item.get("task_id")) for item in concurrent})
        notes.append("ran beside task(s) " + ", ".join(owners) + " in the same `tasks run`; "
                     "writes under their output directories were attributed to them, not to "
                     "this task")
    appends = result.get("memory_appends") or []
    if appends:
        notes.append("memory records appended during the run: "
                     + ", ".join(f"{item.get('id')} (tool {item.get('tool')}, session "
                                 f"{item.get('session')})" for item in appends))
    return {"checked_at": _utc(), "state": "rejected" if problems else "verified",
            "problems": problems, "outputs": outputs, "removed_from_output": removed,
            "unauthorized_changes": unauthorized, "notes": notes, "check": check,
            "memory": None}


def _ledger_event(vault: Path, task_id: str, task_dir: Path, verification: dict) -> dict:
    packet = task_dir / "packet.json"
    task = _read_json(task_dir / "task.json")
    check = verification.get("check")
    return {"event": "verify", "task_id": task_id,
            "definition_sha256": _pin_definition(vault, task_id),
            "packet_id": task.get("shared_packet_id"),
            "packet_sha256": orchestrate.sha256_file(packet) if packet.is_file() else None,
            "produced": [{"path": item["path"], "sha256": item["sha256"]}
                         for item in verification["outputs"]],
            "check_sha256": orchestrate.check_digest(check) if check else None,
            "seed": None, "sampled": [],
            "problems_sha256": orchestrate.sha256_bytes(
                orchestrate.canonical(verification["problems"])),
            "verdict": verification["state"]}


def _record_memory(vault: Path, task: dict, packet: dict, verification: dict) -> dict:
    """A4 hands its result to A3. A memory build without bodies is a note, not a crash.

    The text starts with the task id so a person can find it; memory closes a task
    only through `closes` or `supersedes` (docs/memory.md). It cites the ledger line
    of the verdict, so the memory record and the ledger point at each other.
    """
    # Only vault sources go in `sources`: memory refuses paths under .context
    # (excluded scope), so the outputs travel in the text with their hashes.
    sources = [{"path": item["source_path"], "sha256": item["source_sha256"]}
               for item in packet.get("evidence", [])]
    outputs = "; ".join(f"{item['path']} {item['sha256'][:12]}"
                        for item in verification.get("outputs", []))
    text = f"task {task['id']} {verification['state']}: {task['goal']}"
    if outputs:
        text += f" | outputs: {outputs}"
    ledger = verification.get("ledger")
    if isinstance(ledger, dict) and ledger.get("sha256"):
        text += f" | ledger line {ledger.get('n')} {ledger['sha256'][:16]}"
    try:
        stored = memory.record(vault, kind="result", text=text, sources=sources,
                               state="draft", tool="tasks")
    except NotImplementedError as exc:
        return {"recorded": False, "note": f"memory not available: {exc}"}
    except (OSError, ValueError, KeyError, TypeError) as exc:
        return {"recorded": False, "note": f"memory record failed: {_reason(exc)}"}
    if not isinstance(stored, dict):
        return {"recorded": False, "note": "memory.record returned no record"}
    return {"recorded": True, "id": stored.get("id"),
            "duplicate": bool(stored.get("duplicate")), "note": "recorded in memory"}


