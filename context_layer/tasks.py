def _guarded(function):
    """Every command reports a spec or vault problem instead of a traceback."""
    def wrapper(args: argparse.Namespace) -> int:
        if getattr(args, "rest", None):
            print(f"context-layer tasks: unrecognised arguments: {' '.join(args.rest)}",
                  file=sys.stderr)
            return 2
        try:
            return function(args)
        except (TaskError, backends.BackendError, orchestrate.OrchestrateError) as exc:
            print(f"context-layer tasks: {exc}", file=sys.stderr)
            return 1
    return wrapper


def register(sub: argparse._SubParsersAction) -> None:
    """Attach `context-layer tasks ...` to the CLI."""
    parser = sub.add_parser(
        "tasks",
        help="Dispatch bounded sub-agent tasks and verify what they produced.",
        description="A task hands an agent a goal and a bounded evidence packet, not the "
                    "vault; the agent process can still read the vault unless its host stops "
                    "it. A finished run is pending_review; only `verify` can say verified.")
    inner = parser.add_subparsers(dest="tasks_command", required=True)

    p_new = inner.add_parser("new", help="Create a queued task with a bounded evidence packet.")
    p_new.add_argument("vault")
    p_new.add_argument("--goal", default=None, help="What the agent must produce.")
    p_new.add_argument("--packet", default=None, metavar="ID",
                       help="Deliver this shared packet (`context-layer packet build`) "
                            "instead of running a fresh search.")
    p_new.add_argument("--job", default=None, metavar="FILE",
                       help="Dispatch a validated support-job/v1 file: goal, packet, sources "
                            "and output dir come from it; the worker core and job are sent.")
    p_new.add_argument("--source", action="append", default=[], metavar="GLOB",
                       help="Vault-relative glob the packet may deliver (repeatable).")
    p_new.add_argument("--output-dir", default=None, metavar="REL",
                       help="Vault-relative directory the agent may write to (default: the "
                            "task's own out/). Refused while an unfinished task's output "
                            "directory equals, contains or is inside it.")
    p_new.add_argument("--backend", default="fake", choices=list(backends.BACKENDS))
    p_new.add_argument("--model", default=None)
    p_new.add_argument("--max-turns", type=int, default=None,
                       help="claude backend only: `claude --max-turns`.")
    p_new.add_argument("--max-cost-usd", type=float, default=None, metavar="USD",
                       help="Spend cap for the whole task in host-estimated USD: passed to "
                            "claude as --max-budget-usd (what is left of it each attempt) and "
                            "checked between attempts for every backend.")
    p_new.add_argument("--host-context", choices=list(backends.HOST_CONTEXTS), default="inherit",
                       help="claude backend only: what the host may load besides the packet. "
                            "inherit (default): the user's ~/.claude settings, CLAUDE.md and "
                            "hooks; safe-mode: `claude --safe-mode` (listed by claude --help, "
                            "undocumented in the CLI reference); bare: `claude --bare` (no "
                            "CLAUDE.md discovery or hooks; needs ANTHROPIC_API_KEY).")
    p_new.add_argument("--max-attempts", type=int, default=DEFAULT_MAX_ATTEMPTS)
    p_new.add_argument("--timeout", type=int, default=DEFAULT_TIMEOUT_S, metavar="S")
    p_new.add_argument("--cmd", default=None, metavar="TEMPLATE",
                       help="Backend `cmd` command line, with {prompt_file} and {out_dir}.")
    p_new.add_argument("--top-k", type=int, default=DEFAULT_TOP_K)
    p_new.add_argument("--budget", type=int, default=DEFAULT_BUDGET,
                       help="Evidence characters in the packet.")
    p_new.add_argument("--per-source", type=int, default=DEFAULT_PER_SOURCE)
    p_new.add_argument("--json", action="store_true")
    p_new.set_defaults(func=_guarded(cmd_new), forward_to=None)

    p_run = inner.add_parser("run", help="Run queued tasks, at most --jobs at a time.")
    p_run.add_argument("vault")
    p_run.add_argument("ids", nargs="*", metavar="ID")
    p_run.add_argument("--jobs", type=int, default=1)
    p_run.set_defaults(func=_guarded(cmd_run), forward_to=None)

    p_list = inner.add_parser("list", help="List every task with its state and cost.")
    p_list.add_argument("vault")
    p_list.add_argument("--json", action="store_true")
    p_list.set_defaults(func=_guarded(cmd_list), forward_to=None)

    p_show = inner.add_parser("show", help="Show one task's spec, attempts and verification.")
    p_show.add_argument("target", nargs="+", metavar="ID",
                        help="VAULT ID, or ID with --vault / CONTEXT_LAYER_VAULT.")
    p_show.add_argument("--vault", default=None)
    p_show.add_argument("--json", action="store_true")
    p_show.set_defaults(func=_guarded(cmd_show), forward_to=None)

    p_verify = inner.add_parser("verify", help="Coordinator check: verified or rejected.")
    p_verify.add_argument("target", nargs="+", metavar="ID",
                          help="VAULT ID, or ID with --vault / CONTEXT_LAYER_VAULT.")
    p_verify.add_argument("--vault", default=None)
    p_verify.add_argument("--record", action="store_true",
                          help="Append the outcome to shared memory (memory.record), citing "
                               "the verdict's ledger line.")
    p_verify.add_argument("--json", action="store_true")
    p_verify.set_defaults(func=_guarded(cmd_verify), forward_to=None)

    p_cancel = inner.add_parser("cancel", help="Cancel a queued task or stop a running one.")
    p_cancel.add_argument("target", nargs="+", metavar="ID",
                          help="VAULT ID, or ID with --vault / CONTEXT_LAYER_VAULT.")
    p_cancel.add_argument("--vault", default=None)
    p_cancel.set_defaults(func=_guarded(cmd_cancel), forward_to=None)

    p_recover = inner.add_parser(
        "recover", help="End tasks whose runner is gone: stop the orphaned child, record why.")
    p_recover.add_argument("vault")
    p_recover.add_argument("ids", nargs="*", metavar="ID")
    p_recover.add_argument("--json", action="store_true")
    p_recover.set_defaults(func=_guarded(cmd_recover), forward_to=None)

