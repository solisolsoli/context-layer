def _canonical(payload) -> bytes:
    return orchestrate.canonical(payload)


def _pin_path(vault: Path, task_id: str) -> Path:
    return vault / PINS_DIR / f"{task_id}.json"


def _definition(task: dict, files: dict) -> str:
    return hashlib.sha256(
        _canonical(task) + b"\n" + "\n".join(str(files[name]) for name in PINNED_FILES)
        .encode("ascii", "replace")).hexdigest()


def _write_pin(vault: Path, directory: Path, task: dict) -> dict:
    """Record the definition and the SHA-256 of every file the backend is handed."""
    files = {name: orchestrate.sha256_file(directory / name) for name in PINNED_FILES}
    pin = {"schema": SCHEMA_PIN, "id": task["id"], "pinned_at": _utc(), "task": task,
           "files_sha256": files, "definition_sha256": _definition(task, files)}
    _write_json(_pin_path(vault, task["id"]), pin)
    return pin


def _pinned(vault: Path, directory: Path, task_id: str) -> tuple:
    """(pinned task definition, problems). Any mismatch with the pin is a problem.

    Callers use only the pinned definition, never a re-read of task.json, so a
    backend that rewrites task.json (for example its output_dir) cannot change
    what is checked.
    """
    path = _pin_path(vault, task_id)
    if not path.is_file():
        return None, [f"no dispatch pin at {PINS_DIR}/{task_id}.json; the task "
                      "definition cannot be trusted"]
    try:
        pin = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return None, [f"dispatch pin unreadable: {_reason(exc)}"]
    schema = pin.get("schema") if isinstance(pin, dict) else None
    if (isinstance(schema, str) and schema.startswith(SCHEMA_PIN[:-1])
            and schema != SCHEMA_PIN):
        return None, [f"dispatch pin has format {schema!r}, but this context-layer reads "
                      f"only {SCHEMA_PIN!r}; upgrade context-layer"]
    task = pin.get("task") if isinstance(pin, dict) else None
    files = pin.get("files_sha256") if isinstance(pin, dict) else None
    if (not isinstance(task, dict) or not isinstance(files, dict)
            or pin.get("schema") != SCHEMA_PIN or pin.get("id") != task_id
            or task.get("id") != task_id
            or sorted(files) != sorted(PINNED_FILES)):
        return None, ["dispatch pin is malformed"]
    problems: list = []
    if pin.get("definition_sha256") != _definition(task, files):
        problems.append("dispatch pin does not match its own definition hash")
    for name in PINNED_FILES:
        try:
            actual = orchestrate.sha256_file(directory / name)
        except OSError:
            actual = None
        if actual != files[name]:
            problems.append(f"task definition tampered with after dispatch: {name} "
                            "no longer matches its pinned SHA-256")
    return task, problems


def _pin_definition(vault: Path, task_id: str) -> str | None:
    try:
        pin = json.loads(_pin_path(vault, task_id).read_text(encoding="utf-8"))
        return pin.get("definition_sha256") if isinstance(pin, dict) else None
    except (OSError, ValueError):
        return None


