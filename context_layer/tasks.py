def _ignored(relative: str) -> bool:
    """The tool's own derived state, which other commands rewrite while a task runs.

    The whole task area (every task's bookkeeping, the ledger, leases), the run
    folder, the index and link graph (`index` rewrites both), the activation
    trace, shared packets (content-addressed, re-verified on every read) and the
    memory store's lock, mirror and staging files. `records.jsonl` itself is
    watched: an append is attributed to the tool and session that wrote it, any
    other change is reported.
    """
    if relative == ".context-runs" or relative.startswith(".context-runs/"):
        return True
    if relative == TASKS_DIR or relative.startswith(TASKS_DIR + "/"):
        return True
    if relative == ".context/activation.json" or relative.startswith(".context/packets/"):
        return True
    if relative.startswith(".context/memory/") and relative != MEMORY_RECORDS:
        return True
    if relative == ".context/sessions" or relative.startswith(".context/sessions/"):
        return True   # the memory session record, written while a task runs
    parts = relative.split("/")
    if len(parts) == 2 and parts[0] == ".context":
        name = parts[1].lstrip(".")
        return name.startswith(("index", "graph.sqlite", "graph-"))
    return False


def _manifest(vault: Path) -> dict:
    """path -> fingerprint of every watched entry. Nothing is followed.

    A regular file is hashed; a symlink, to a file or to a directory, is recorded
    as its target; anything else by its type. The memory store also records its
    size, so an append can be told from a rewrite.
    """
    manifest: dict = {}
    pending = [vault]
    while pending:
        directory = pending.pop()
        try:
            entries = list(os.scandir(directory))
        except OSError as exc:
            manifest[Path(directory).relative_to(vault).as_posix() + "/"] = \
                f"unreadable:{exc.errno}"
            continue
        for entry in entries:
            relative = Path(entry.path).relative_to(vault).as_posix()
            if _ignored(relative):
                continue
            try:
                info = entry.stat(follow_symlinks=False)
            except OSError as exc:
                manifest[relative] = f"unreadable:{exc.errno}"
                continue
            if stat.S_ISLNK(info.st_mode):
                try:
                    manifest[relative] = "symlink:" + os.readlink(entry.path)
                except OSError:
                    manifest[relative] = "symlink:?"
            elif stat.S_ISDIR(info.st_mode):
                pending.append(Path(entry.path))
            elif stat.S_ISREG(info.st_mode):
                try:
                    digest = _sha256_nofollow(entry.path)
                except OSError as exc:
                    manifest[relative] = f"unreadable:{exc.errno}"
                    continue
                manifest[relative] = (f"append:{info.st_size}:{digest}"
                                      if relative == MEMORY_RECORDS else digest)
            else:
                manifest[relative] = f"special:{stat.S_IFMT(info.st_mode)}"
    return manifest


def _memory_appends(vault: Path, before, after) -> list | None:
    """The records appended to records.jsonl between two fingerprints, or None when the
    file changed some other way (rewritten, truncated, removed)."""
    if not isinstance(after, str) or not after.startswith("append:"):
        return None
    try:
        new_size = int(after.split(":")[1])
        data = (vault / MEMORY_RECORDS).read_bytes()[:new_size]
    except (OSError, ValueError, IndexError):
        return None
    old_size, old_digest = 0, None
    if before is not None:
        if not isinstance(before, str) or not before.startswith("append:"):
            return None
        _, size, old_digest = before.split(":", 2)
        old_size = int(size)
    if len(data) < old_size or (old_digest is not None
                                and hashlib.sha256(data[:old_size]).hexdigest() != old_digest):
        return None
    appended = []
    for _, line in orchestrate.jsonl_lines(data[old_size:]):
        if not line.strip():
            continue
        try:
            record = json.loads(line)
        except ValueError:
            return None
        if not isinstance(record, dict):
            return None
        appended.append({key: record.get(key) for key in ("id", "kind", "tool", "session")})
    return appended


def _classify(before: dict, after: dict, allowed_relative: str, others: dict | None = None,
              vault: Path | None = None) -> tuple:
    """(unauthorized, concurrent_task_writes, memory_appends) between two manifests.

    Changes inside the allowed output directory are the attempt's own. A change
    inside the output directory of another task run by the same `tasks run` is
    that task's (leases keep the directories apart) and is recorded, not
    reported. A pin or a job file *created* in the window is another dispatch. A
    pure append to the memory store is attributed by its records' tool and session.
    """
    permitted = allowed_relative.rstrip("/")
    unauthorized: list = []
    concurrent: list = []
    appends: list = []
    for relative in sorted(set(before) | set(after)):
        if before.get(relative) == after.get(relative):
            continue
        if relative == permitted or relative.startswith(permitted + "/"):
            continue
        change = "created" if relative not in before else \
            "deleted" if relative not in after else "changed"
        owner = next((task_id for task_id, out in (others or {}).items()
                      if relative == out.rstrip("/") or relative.startswith(out.rstrip("/") + "/")),
                     None)
        if owner is not None:
            concurrent.append({"path": relative, "change": change, "task_id": owner})
            continue
        if change == "created" and relative.startswith(PINS_DIR + "/") \
                and relative.count("/") == PINS_DIR.count("/") + 1:
            continue
        if change == "created" and _new_job_file(relative):
            continue
        if relative == MEMORY_RECORDS and vault is not None:
            records = _memory_appends(vault, before.get(relative), after.get(relative))
            if records is not None:
                appends += records
                continue
        unauthorized.append({"path": relative, "change": change})
    return unauthorized, concurrent, appends


def _new_job_file(relative: str) -> bool:
    """A file `job new` writes once and never rewrites (jobs are immutable)."""
    parts = relative.split("/")
    if parts[:2] != [".context", "jobs"]:
        return False
    if len(parts) == 3:
        return parts[2] == orchestrate.CORE_NAME
    return (len(parts) == 5 and parts[3].startswith("attempt-")
            and parts[4] in ("job.md", "input-manifest.json", "payload.json"))


def _changes(before: dict, after: dict, allowed_relative: str) -> list:
    """Everything that changed outside the allowed output directory (see _classify)."""
    return _classify(before, after, allowed_relative)[0]


