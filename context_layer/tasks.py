def _claim(directory: Path, task_id: str, purpose: str = "run") -> dict | None:
    """Create runner.json exclusively: exactly one process ever runs (or cancels) a task."""
    record = {"schema": SCHEMA_RUNNER, "task_id": task_id, "purpose": purpose,
              "runner_pid": os.getpid(), "host": _host(), "started_at": _utc(),
              "heartbeat_at": _utc(), "attempt": None, "child_pgid": None, "ended_at": None}
    if _create_exclusive(directory / RUNNER_NAME, json.dumps(record, indent=2) + "\n"):
        return record
    return None


class _Beat:
    """The runner's heartbeat and child record in runner.json, throttled to HEARTBEAT_S."""

    def __init__(self, directory: Path, claim: dict):
        self.directory = directory
        self.claim = dict(claim)
        self.last = 0.0

    def __call__(self, force: bool = False, **fields) -> None:
        self.claim.update(fields)
        now = time.monotonic()
        if not force and not fields and now - self.last < HEARTBEAT_S:
            return
        self.last = now
        self.claim["heartbeat_at"] = _utc()
        try:
            _write_json(self.directory / RUNNER_NAME, self.claim)
        except OSError:
            pass  # a missed heartbeat is not a failed task

    def end(self, state: str | None = None) -> None:
        self(force=True, child_pgid=None, ended_at=_utc(), final_state=state)


def _alive(pid) -> bool:
    return process_is_alive(pid)


def _stop_group(pgid) -> str:
    """SIGTERM a recorded child process group, then SIGKILL what is left of it."""
    if not isinstance(pgid, int) or isinstance(pgid, bool) or pgid <= 1:
        return "no child process group was recorded"
    if os.name == "nt":
        # The runner owns a kill-on-close Job Object; a dead runner has already
        # closed it. Never signal a bare PID that may have been reused.
        return ("its runner-owned process job has exited" if not process_is_alive(pgid)
                else "cannot safely signal a Windows child by PID; runner job is still active")
    for number in (signal.SIGTERM, signal.SIGKILL):
        try:
            os.killpg(pgid, number)
        except ProcessLookupError:
            return ("its child process group had already exited" if number == signal.SIGTERM
                    else f"child process group {pgid} stopped")
        except PermissionError:
            return f"child process group {pgid} belongs to another user; not signalled"
        deadline = time.monotonic() + KILL_GRACE_S
        while time.monotonic() < deadline:
            try:
                os.killpg(pgid, 0)
            except ProcessLookupError:
                return f"child process group {pgid} stopped"
            except PermissionError:
                break
            time.sleep(POLL_S)
    return f"child process group {pgid} sent SIGKILL"


def _lease_dir(vault: Path) -> Path:
    return _tasks_root(vault) / LEASES_DIR


def _acquire_lease(vault: Path, task_id: str, out_relative: str) -> tuple:
    """(lease path, None) or (None, why): no two live runs share an output directory.

    Under the registry lock: a lease whose holder is dead on this host is removed;
    a live lease on an equal, containing or contained directory refuses this run.
    """
    with _registry_lock(vault):
        directory = _lease_dir(vault)
        directory.mkdir(parents=True, exist_ok=True)
        for path in sorted(directory.glob("*.json")):
            try:
                lease = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                path.unlink(missing_ok=True)
                continue
            if not isinstance(lease, dict):
                path.unlink(missing_ok=True)
                continue
            if lease.get("host") == _host() and not _alive(lease.get("runner_pid")):
                path.unlink(missing_ok=True)
                continue
            held = lease.get("output_dir")
            if isinstance(held, str) and _overlap(held, out_relative):
                return None, (f"output directory {out_relative} overlaps {held}, leased by "
                              f"task {lease.get('task_id')} (runner pid "
                              f"{lease.get('runner_pid')})")
        name = hashlib.sha256(_fold(out_relative).encode("utf-8")).hexdigest()[:32] + ".json"
        record = {"schema": SCHEMA_LEASE, "task_id": task_id, "output_dir": out_relative,
                  "runner_pid": os.getpid(), "host": _host(), "acquired_at": _utc()}
        path = directory / name
        if not _create_exclusive(path, json.dumps(record, indent=2) + "\n"):
            return None, f"output directory {out_relative} is leased by another run"
        return path, None


def _release_lease(path: Path | None) -> None:
    if path is None:
        return
    try:
        lease = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return
    if isinstance(lease, dict) and lease.get("runner_pid") == os.getpid() \
            and lease.get("host") == _host():
        path.unlink(missing_ok=True)


