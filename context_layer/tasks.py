def _save(vault: Path, task_id: str, result: dict) -> dict:
    result["updated_at"] = _utc()
    with _MIRROR_LOCK:
        _write_json(_tasks_root(vault) / task_id / "result.json", result)
        _write_mirror(vault)
    return result


def _finish(vault: Path, task_id: str, result: dict, state: str, reason: str) -> dict:
    if state not in STATES:
        raise TaskError(f"not a task state: {state}")
    result["state"] = state
    result["reason"] = reason
    result["ended_at"] = _utc()
    # The flag file, not this copy of result.json, is what `cancel` wrote: the
    # runner and the cancelling process are two processes with two copies.
    result["cancel_requested"] = _cancel_flag(_tasks_root(vault) / task_id).exists()
    seen: dict = {}
    concurrent: list = []
    appends: list = []
    for attempt in result.get("attempts", []):
        for change in attempt.get("unauthorized_changes", []):
            seen[change["path"]] = change
        concurrent += attempt.get("concurrent_task_writes") or []
        appends += attempt.get("memory_appends") or []
    result["unauthorized_changes"] = [seen[path] for path in sorted(seen)]
    result["concurrent_task_writes"] = concurrent
    result["memory_appends"] = appends
    return _save(vault, task_id, result)


def _all_tasks(vault: Path, problems: list | None = None) -> list:
    """(task, result) for every readable task; an unreadable one goes to `problems`."""
    root = _tasks_root(vault)
    rows: list = []
    if not root.is_dir():
        return rows
    for entry in sorted(root.iterdir()):
        if entry.name.startswith(".") or not entry.is_dir() \
                or not (entry / "task.json").is_file():
            continue
        try:
            rows.append((_read_json(entry / "task.json"), _read_json(entry / "result.json")))
        except TaskError as exc:
            if problems is not None:
                problems.append((entry.name, str(exc)))
    return rows


def _totals(attempts: list) -> dict:
    """Token, cost and wall totals over attempts; what cannot be summed is counted.

    Usage that is missing, negative, non-finite or not a whole number is unknown,
    never zero; so is a cost that is not a finite, non-negative number.
    """
    usage = backends.zero_usage()
    cost = 0.0
    wall = 0.0
    usage_unknown = 0
    cost_unknown = 0
    models: dict = {}
    for attempt in attempts:
        seconds = backends.amount(attempt.get("wall_s"))
        wall += seconds or 0.0
        spent = backends.amount(attempt.get("total_cost_usd"))
        if spent is None:
            cost_unknown += 1
        else:
            cost += spent
        counts, _ = backends.check_usage(attempt.get("usage"))
        if counts is None:
            usage_unknown += 1
        else:
            for key in backends.USAGE_KEYS:
                usage[key] += counts[key]
        model_usage, _ = backends.check_model_usage(attempt.get("model_usage"))
        for model, entry in (model_usage or {}).items():
            total = models.setdefault(model, {key: 0 for key in backends.MODEL_USAGE_KEYS})
            for key in backends.MODEL_USAGE_KEYS:
                total[key] += entry.get(key, 0)
            if "costUSD" in entry:
                total["costUSD"] = round(total.get("costUSD", 0.0) + entry["costUSD"], 6)
    return {"attempts": len(attempts), "usage": usage, "total_cost_usd": round(cost, 6),
            "wall_s": round(wall, 3), "usage_unknown": usage_unknown,
            "cost_unknown": cost_unknown, "model_usage": models}


def _cell(value: str) -> str:
    return str(value).replace("|", r"\|").replace("\n", " ").replace("\r", " ")


def _attestations(vault: Path) -> tuple:
    """({task id: latest verify line}, ledger problems)."""
    entries, problems = orchestrate.read_ledger(vault)
    latest: dict = {}
    for entry in entries:
        record = entry["record"]
        if record.get("event") == "verify" and isinstance(record.get("task_id"), str):
            latest[record["task_id"]] = entry
    return latest, problems


def _unattested(task_id: str, result: dict, latest: dict, problems: list) -> str | None:
    """Why a verified/rejected state is not backed by the ledger, or None when it is."""
    state = result.get("state")
    if state not in ATTESTED:
        return None
    if problems:
        return "the ledger chain is broken: " + problems[0]
    entry = latest.get(task_id)
    if entry is None:
        return "no ledger line records this verdict"
    if entry["record"].get("verdict") != state:
        return f"the ledger's last verdict is {entry['record'].get('verdict')}"
    cited = ((result.get("verification") or {}).get("ledger") or {}).get("sha256")
    if cited and cited != entry["sha256"]:
        return "result.json cites another ledger line"
    return None


def _write_mirror(vault: Path) -> Path:
    """Regenerate TASKS.md. Derived from result.json; never a second source of truth.

    It does not read the verification ledger (that would make every save cost a
    full ledger read); `tasks list` and `tasks show` mark unattested verdicts.
    """
    problems: list = []
    rows = _all_tasks(vault, problems)
    lines = [MIRROR_HEADER, "", "# Tasks", "",
             f"Derived from `{TASKS_DIR}/` at {_utc()}. Only `context-layer tasks verify` "
             "can produce `verified`; a finished run stops at `pending_review`. This file "
             "does not check the verification ledger: `context-layer tasks list` marks a "
             "verdict without its ledger line UNATTESTED. Cost is the host's estimate.", "",
             "| Task | State | Backend | Attempts | Tokens in/out | Host-est. USD | Wall s | Goal |",
             "| --- | --- | --- | ---: | ---: | ---: | ---: | --- |"]
    for task, result in rows:
        totals = _totals(result.get("attempts", []))
        goal = task.get("goal", "")
        state = result.get("state", "?")
        lines.append("| `{id}` | {state} | {backend} | {attempts} | {tokens} | {cost} | "
                     "{wall} | {goal} |".format(
                         id=_cell(task.get("id", "?")), state=_cell(state),
                         backend=_cell(task.get("backend", "?")), attempts=totals["attempts"],
                         tokens="{0}/{1}".format(totals["usage"]["input_tokens"],
                                                 totals["usage"]["output_tokens"]),
                         cost="{0:.6f}".format(totals["total_cost_usd"]),
                         wall="{0:.3f}".format(totals["wall_s"]),
                         goal=_cell(goal if len(goal) <= 60 else goal[:57] + "...")))
    for name, _ in problems:
        lines.append(f"| `{_cell(name)}` | unreadable |  |  |  |  |  | (task files cannot be "
                     "read) |")
    if not rows and not problems:
        lines.append("| _none_ |  |  |  |  |  |  |  |")
    lines += ["", "States: " + ", ".join(STATES) + ".", ""]
    path = _tasks_root(vault) / MIRROR_NAME
    orchestrate.atomic_write(path, "\n".join(lines))
    return path


